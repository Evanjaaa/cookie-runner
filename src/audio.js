// อยากปรับเสียงให้ถูกใจ ลองแก้ 3 อย่างนี้:
//   type  — square = 8-bit / sine = นุ่ม / sawtooth = แสบ / triangle = กลาง ๆ
//   ช่วงความถี่ — สูงขึ้น = สดใสขึ้น
//   dur   — สั้นลง = กระชับขึ้น

