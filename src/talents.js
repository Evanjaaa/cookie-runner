// เก็บผ่าน loadPref/savePref ซึ่งชั้นซิงก์ดันขึ้นคลาวด์ให้เองอยู่แล้ว (ดู storage.js)
// ติดได้ทีละใบ (ตามแผนเวอร์ชันแรก) — เก็บเป็น id เดียว ไม่ใช่รายการ

const PREF = 'talent';

/** ใบที่ติดตั้งอยู่ — null ถ้าไม่ได้ติด หรือใบที่บันทึกไว้ถูกปิดใช้ไปแล้ว */
export function getEquippedTalent() {
  const t = talentById(loadPref(PREF, null));
  return t && isUnlocked(t) ? t : null;
}

/** ติดตั้ง/ถอด — ส่ง null เพื่อถอด */
export function setEquippedTalent(id) {
  const t = id ? talentById(id) : null;
  if (t && !isUnlocked(t)) return false;
  savePref(PREF, t ? t.id : null);
  return true;
}

/**
 * ปลดล็อกแล้วหรือยัง
 *
 * ตอนนี้เกมยังไม่มีทางได้การ์ด (กาช่า/กิจกรรม) ใบที่เปิดใช้งานได้จึงถือว่ามีทุกใบ
 * วันที่มีระบบแจกการ์ด เปลี่ยนฟังก์ชันนี้ฟังก์ชันเดียว หน้าจอกับตัวรันไม่ต้องแก้
 */
export function isUnlocked(t) {
  return t.status === 'ready';
}

/** แปลงเฟรมเป็นข้อความวินาทีสำหรับหน้าจอ */
export function secText(frames) {
  const s = frames / 60;
  return (Number.isInteger(s) ? s : s.toFixed(1)) + ' วินาที';
}
