// นาฬิกาของเกมที่อิงเวลาเซิร์ฟเวอร์
//
// ── ทำไมไม่ใช้ Date.now() ตรง ๆ ──
// ระบบเลี้ยงน้อง (หิว ง่วง เพดาน EXP รายวัน) นับจากเวลาจริงทั้งหมด
// ถ้าเชื่อนาฬิกาเครื่อง แค่เลื่อนวันที่ในมือถือไปข้างหน้าก็เลี้ยงน้องโตได้ในนาทีเดียว
//
// ทุกคำตอบจากเซิร์ฟเวอร์มีหัว Date ติดมาเสมอ cloud.js ส่งค่านั้นมาที่นี่
// แล้วเราจำแค่ "นาฬิกาเครื่องคลาดไปเท่าไหร่" — อ่านเวลาเมื่อไหร่ก็บวกส่วนต่างนี้
// ไม่มีเน็ต / ยังไม่เคยคุยกับเซิร์ฟเวอร์ = ส่วนต่างเป็นศูนย์ ใช้นาฬิกาเครื่องไปก่อน
// ─────────────────────────────────────────────────────────────

let skew = 0;

/**
 * หัว Date ละเอียดแค่วินาที — ส่วนต่างที่ต่ำกว่าสองวินาทีถือว่าเป็นเศษจากการปัด
 * ไม่ขยับตาม ไม่งั้นตัวเลขเวลาที่โชว์จะกระตุกไปมาทุกครั้งที่มีคำตอบเข้ามา
 */
export function noteServerDate(header) {
  noteServerTime(Date.parse(header || ''));
}

/**
 * เวลาเซิร์ฟเวอร์เป็นมิลลิวินาที — จาก RPC server_now() (ดู supabase/cats.sql)
 * ทางนี้แน่นอนกว่าหัว Date เพราะเบราว์เซอร์อาจไม่ยอมให้อ่านหัว Date ข้ามโดเมน
 */
export function noteServerTime(t) {
  if (!Number.isFinite(t)) return;
  const d = t - Date.now();
  if (Math.abs(d - skew) > 2000) skew = d;
}

/** เวลาปัจจุบัน (มิลลิวินาที) ตามนาฬิกาเซิร์ฟเวอร์ */
export function now() {
  return Date.now() + skew;
}

/** ชื่อวันแบบ YYYY-MM-DD ตามเวลาไทย — ใช้แบ่ง "วันนี้" ของเพดานรายวัน */
export function dayKey(ms = now()) {
  return new Date(ms + 7 * 3600 * 1000).toISOString().slice(0, 10);
}
