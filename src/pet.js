import { loadPref, savePref } from './storage.js';

/**
 * คีย์ใน pref
 *
 * ── คูลดาวน์อยู่ในเครื่อง ไม่ขึ้นคลาวด์ ──
 * ชั้นซิงก์จับคู่คีย์ pref กับคอลัมน์ในฐานข้อมูลแบบระบุชื่อทีละตัว (ดู net/sync.js)
 * ตัวนี้ไม่อยู่ในรายการ จึงอยู่แค่เครื่องนี้ แปลว่าคนที่เล่นสองเครื่องกดได้สองรอบ
 *
 * รับผลข้อนี้ไว้โดยตั้งใจ เพราะทางแก้คือเพิ่มคอลัมน์ในฐานข้อมูลกับย้ายสคีมา
 * เพื่อกันเรื่องที่เสียแค่ทองไม่กี่พันในเกมผู้เล่นคนเดียว ซึ่งไม่คุ้มกัน
 */
const KEY = 'petAt';

/** เว้นสองชั่วโมงต่อครั้ง */
export const PET_COOLDOWN_MS = 2 * 60 * 60 * 1000;

/**
 * ตารางของขวัญ — ยิ่งได้เยอะ โอกาสยิ่งน้อย
 *
 * น้ำหนักเป็นจำนวนเต็มรวมกันได้ 1000 พอดี อ่านเป็นเปอร์เซ็นต์ได้ทันที
 * โดยหารสิบ (300 = 30%) และไม่มีปัญหาทศนิยมปัดเพี้ยนตอนสุ่ม
 *
 * ── ทำไมมีช่อง "ไม่ได้ทอง" ถึง 30% ──
 * ถ้าได้ทองทุกครั้ง ปุ่มนี้จะกลายเป็นแค่ปุ่มรับเงินที่ต้องกดทุกสองชั่วโมง
 * ช่องที่น้องแค่มองแล้วร้องเมี้ยวทำให้การกดแต่ละครั้งมีผลลัพธ์ให้ลุ้นจริง
 * และของที่ได้ตอนได้จริงจึงรู้สึกว่าได้ ไม่ใช่ของที่ควรได้อยู่แล้ว
 *
 * ── ค่าเฉลี่ยที่ตั้งใจ ──
 * 1,295 ทองต่อครั้ง = ราวหนึ่งในสี่ของค่าสุ่มชุดหนึ่งครั้ง (OUTFIT_COST 5,000)
 * เล่นวันละสองสามรอบจึงได้สุ่มฟรีเพิ่มราวสัปดาห์ละครั้ง ไม่ล้มระบบหาทองทางอื่น
 */
export const PET_GIFTS = [
  { gold: 0,    weight: 300 },   // น้องมองแล้วร้องเมี้ยวเฉย ๆ
  { gold: 1000, weight: 340 },
  { gold: 2000, weight: 200 },
  { gold: 3000, weight: 100 },
  { gold: 4000, weight: 45 },
  { gold: 5000, weight: 15 },
];

const TOTAL = PET_GIFTS.reduce((s, g) => s + g.weight, 0);

/**
 * เวลาที่กดครั้งล่าสุด
 *
 * ── ทำไมต้องกันค่าที่อยู่ในอนาคต ──
 * คนที่ตั้งนาฬิกาเครื่องเดินหน้าไปแล้วตั้งกลับ จะเหลือค่าที่มากกว่าเวลาปัจจุบัน
 * ค้างอยู่ ถ้าไม่กัน ปุ่มจะล็อกยาวเป็นวันโดยไม่มีทางแก้ นับเป็นพร้อมกดไปเลย
 * ดีกว่าปล่อยให้เกมพังในมือคนที่ไม่ได้ตั้งใจโกงด้วยซ้ำ
 */
function lastAt() {
  const v = Number(loadPref(KEY, 0)) || 0;
  return v > Date.now() ? 0 : v;
}

/** เหลืออีกกี่มิลลิวินาทีถึงจะกดได้ — 0 คือกดได้เลย */
export function petLeftMs() {
  return Math.max(0, lastAt() + PET_COOLDOWN_MS - Date.now());
}

export function canPet() {
  return petLeftMs() === 0;
}

/** เริ่มนับคูลดาวน์ใหม่ — ต้องเรียกก่อนเล่นแอนิเมชัน ไม่ใช่หลัง (ดูเหตุผลใน main.js) */
export function markPetted() {
  savePref(KEY, Date.now());
}

/** สุ่มของขวัญหนึ่งชิ้น คืน { gold } โดย gold = 0 แปลว่าน้องแค่มอง */
export function rollPetGift() {
  let r = Math.random() * TOTAL;
  for (const g of PET_GIFTS) {
    r -= g.weight;
    if (r < 0) return { gold: g.gold };
  }
  return { gold: 0 };
}

/** "1:59:04" หรือ "04:12" เมื่อเหลือไม่ถึงชั่วโมง — ใช้เขียนบนปุ่ม */
export function petLeftText(ms = petLeftMs()) {
  const s = Math.ceil(ms / 1000);
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = s % 60;
  const pad = (n) => String(n).padStart(2, '0');
  return h > 0 ? `${h}:${pad(m)}:${pad(sec)}` : `${pad(m)}:${pad(sec)}`;
}
