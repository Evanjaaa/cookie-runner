const PREF_KEY = 'skill';

export function skillById(id) {
  return SKILLS.find((s) => s.id === id) || null;
}

/** สกิลที่ทุกคนมีตั้งแต่เริ่ม — ใช้เป็นค่าตั้งต้นและเป็นทางหนีเวลาข้อมูลเซฟเพี้ยน */
export function starterSkill() {
  return SKILLS.find((s) => s.starter);
}

/** ความคืบหน้าของภารกิจปลดล็อก — อ่านตัวนับสดจาก stats.js ทุกครั้ง ไม่เก็บสำเนา */
export function skillProgress(sk) {
  if (!sk.unlock) return { now: 1, goal: 1, ratio: 1 };
  const now = Math.min(sk.unlock.goal, Number(loadStats()[sk.unlock.stat]) || 0);
  return { now, goal: sk.unlock.goal, ratio: now / sk.unlock.goal };
}

/**
 * ปลดแล้วหรือยัง — คำนวณจากตัวนับทุกครั้ง ไม่ได้เก็บ "ปลดแล้ว" แยกไว้
 * ตัวนับใน stats.js เพิ่มอย่างเดียว สกิลที่เคยปลดแล้วจึงไม่มีทางกลับไปล็อกอีก
 * และไม่มีทางที่ "สถานะปลด" กับ "ตัวนับจริง" จะหลุดออกจากกัน
 */
export function isSkillUnlocked(sk) {
  return !!sk && (sk.starter || skillProgress(sk).ratio >= 1);
}

/**
 * สกิลที่ติดตั้งอยู่ — ถ้าที่บันทึกไว้ไม่มีแล้วหรือยังไม่ปลด ถอยกลับไปสกิลตั้งต้น
 * (เช่นสกิลที่เคยทดสอบในหน้าดีบั๊กแล้วรีเซ็ตสถิติ) เกมจึงมีสกิลให้ใช้เสมอ ไม่มีทางได้ null
 */
export function getEquippedSkill() {
  const sk = skillById(loadPref(PREF_KEY, starterSkill().id));
  return isSkillUnlocked(sk) ? sk : starterSkill();
}

/** ติดตั้งสกิล — คืน false ถ้ายังไม่ปลด (หน้าจอไม่ควรปล่อยให้กดถึงตรงนี้ แต่กันไว้อีกชั้น) */
export function setEquippedSkill(id) {
  const sk = skillById(id);
  if (!isSkillUnlocked(sk)) return false;
  savePref(PREF_KEY, sk.id);
  return true;
}

/**
 * ปลดทุกสกิล (ปุ่มในแผงทดสอบ) — ดันตัวนับภารกิจให้ถึงเป้า ไม่ได้ตั้งธงปลดแยก
 * สกิลจึงปลดผ่านทางเดียวกับเล่นจริง หน้าสกิลเห็นหลอดเต็ม และไม่มีสถานะที่หลุดจากตัวนับ
 * คืนจำนวนสกิลที่เพิ่งปลดในครั้งนี้
 */
export function unlockAllSkills() {
  let n = 0;
  for (const sk of SKILLS) {
    if (sk.unlock && raiseStat(sk.unlock.stat, sk.unlock.goal)) n++;
  }
  return n;
}

