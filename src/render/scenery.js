// ── ปัญหาที่ไฟล์นี้แก้ ──
// ของประกอบฉากเคยวางด้วยการวนเศษ: x = wrap(ฐาน − cam × depth, span) − ระยะเยื้อง
// ซึ่งถูกเฉพาะตอน span กว้างกว่าจอบวกความกว้างของชิ้นนั้น ถ้าแคบกว่านั้น ตำแหน่ง
// ที่ชิ้นนั้นโผล่กลับมาหลังวนครบรอบจะอยู่ "กลางจอ" — ผู้เล่นเห็นของผุดขึ้นมาเฉย ๆ
// (วัดจากของจริง: หน้าต่างในครัวโผล่ที่ x=140, ปราสาทหิมะโผล่ที่ x=208)
//
// ── ทำไมของไกลถึงพังบ่อยกว่าของใกล้ ──
// ชั้นที่อยู่ไกลเลื่อนช้า (depth 0.1 = กล้องเดิน 10 ก้าว ชั้นนั้นเลื่อน 1 ก้าว)
// ของจะข้ามจอได้ต้องใช้ระยะกล้อง W / depth ซึ่งที่ depth 0.1 คือเกือบหมื่นพิกเซล
// ถ้าอยากให้ของโผล่ถี่กว่านั้น ทางเดียวคือย่อ span ลง = ทำให้มันผุดกลางจอ
// ของไกลจึง "ต้อง" ผ่านช้า นั่นคือธรรมชาติของการมองวิวจากรถ ไม่ใช่ข้อจำกัดที่ควรเลี่ยง
// อยากให้ของผ่านถี่ขึ้นให้ขยับ depth เข้าใกล้ตัว ไม่ใช่บีบระยะห่าง
//
// ── กติกาเดียวของไฟล์นี้ ──
// ระยะห่างระหว่างชิ้น (every) ต้องไม่น้อยกว่า ความกว้างจอ + ความกว้างชิ้น
// มิฉะนั้นชิ้นถัดไปจะโผล่ทั้งที่ชิ้นก่อนหน้ายังไม่พ้นจอ — ฟังก์ชันนี้เตือนให้ตอนพัฒนา
// ─────────────────────────────────────────────────────────────
import { VIEW } from '../config.js';

const { W } = VIEW;

/**
 * เดินทีละ "ช่อง" ในพิกัดโลก แล้ววาดเฉพาะช่องที่มองเห็นอยู่
 *
 * @param cam   กล้องในพิกัดโลก
 * @param depth ตัวคูณ parallax (0 = ไกลจนนิ่ง, 1 = เลื่อนเท่าพื้น)
 * @param every ระยะห่างระหว่างช่อง วัดในพิกัดของชั้นนั้นเอง
 * @param pad   ความกว้างของชิ้นที่กว้างที่สุด (เผื่อให้เริ่มวาดก่อนเข้าจอ)
 * @param draw  (i, x) => void — i = เลขช่องในโลก (ชิ้นเดิมได้เลขเดิมตลอดเกม)
 *
 * ── ทำไมส่งเลขช่องออกไปด้วย ──
 * ให้ผู้เรียกเอาไปสุ่มหน้าตาแบบคงที่ (hash(i)) ชิ้นที่ x เดิมในโลกจึงหน้าตาเดิมเสมอ
 * วิ่งผ่านกี่รอบก็เห็นของชิ้นเดียวกัน ไม่ใช่ของที่สุ่มใหม่ทุกครั้งที่เข้าจอ
 */
export function placed(cam, depth, every, pad, draw) {
  const shift = cam * depth;
  const from = Math.floor((shift - pad) / every);
  const to = Math.ceil((shift + W + pad) / every);
  for (let i = from; i <= to; i++) draw(i, i * every - shift);
}

/**
 * ระยะห่างที่น้อยที่สุดที่ยังไม่ทำให้ของผุดกลางจอ
 * ใช้ตอนตั้งค่า every: every = Math.max(ที่อยากได้, minGap(ความกว้างชิ้น))
 */
export function minGap(itemW) {
  return W + itemW;
}

/**
 * ระยะกล้องที่ต้องเดินกว่าของชั้นนี้จะผ่านหน้าจอหนึ่งชิ้น (ไว้ตรวจจังหวะตอนจูน)
 * เช่น depth 0.2 every 1260 → 6300px ≈ 15 วินาทีที่ความเร็ววิ่งปกติ
 */
export function passEvery(depth, every) {
  return every / depth;
}
