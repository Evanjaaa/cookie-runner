// ฉาก "ห้องเวิร์กช็อปแมว" — หน้าก่อนเริ่มวิ่ง
//
// ── ฉากนี้เป็นภาพนิ่งทั้งฉาก ──
// ไม่มีการเลื่อน ไม่มีพารัลแลกซ์ ไม่มีชิ้นไหนขยับเลยแม้แต่ชิ้นเดียว
// ต่างจากฉากอาณาจักรหน้าแรกซึ่งของในฉากขยับอยู่กับที่
//
// เหตุผลไม่ใช่เรื่องประหยัดแรงเครื่อง แต่เป็นเรื่องหน้าที่ของหน้า:
// หน้านี้มีอยู่เพื่อให้ผู้เล่นอ่านคำพูดของน้องแล้วกดเริ่ม ของที่ขยับในฉาก
// จะแย่งสายตาไปจากสองอย่างนั้น ซึ่งเป็นสิ่งเดียวที่หน้านี้ต้องการให้ทำ
//
// ── ของที่ยืมมาจากฉากข้างนอก ──
// ลูกไหมพรม ขวดยา โคมไฟ เพชร ใช้ตัวเดียวกับ render/kingdom/props.js
// ชิ้นพวกนั้นรับ "เวลา" เข้าไปด้วย แต่เขียนเป็นฟังก์ชันบริสุทธิ์ทั้งหมด
// ส่งเวลาค่าคงที่เข้าไป ผลลัพธ์จึงคงที่ตาม — ได้ภาพนิ่งโดยไม่ต้องเขียนของซ้ำอีกชุด
// นี่คือเหตุผลที่ตอนสร้างคลังชิ้นส่วนถึงบังคับให้ทุกชิ้นเป็นฟังก์ชันบริสุทธิ์
// ─────────────────────────────────────────────────────────────
import { VIEW, GROUND_Y } from '../../config.js';
import { ROOM } from './palette.js';
import { KINGDOM } from '../kingdom/palette.js';
import { PROPS as OUT } from '../kingdom/props.js';
import * as R from './props.js';

const { W, H } = VIEW;

/** เส้นแบ่งกำแพงกับพื้น — ต่ำกว่านี้คือพื้นที่น้องยืนได้ */
const FLOOR_Y = 286;

/** เวลาที่หยุดนิ่ง — ส่งเข้าไปในชิ้นส่วนที่ยืมมาจากฉากข้างนอก ดูหัวไฟล์ */
const FROZEN = 0;

/**
 * จานสีสำหรับของที่ยืมมา
 * เอาสีของเล่นจากฉากข้างนอกมาใช้ (ลูกไหมสีเดียวกันทั้งเกม) แต่เปลี่ยนสีเส้นขอบ
 * เป็นน้ำตาลของห้อง ไม่งั้นของยืมจะมีเส้นอมม่วงอยู่ชิ้นเดียวท่ามกลางเส้นน้ำตาล
 */
const ITEM = { ...KINGDOM, line: ROOM.line };

const yarn = (ctx, x, y, s, seed) => OUT.yarnBall(ctx, x, y, s, ITEM, FROZEN, seed);
const potion = (ctx, x, y, s, seed) => OUT.potion(ctx, x, y, s, ITEM, FROZEN, seed);
const gem = (ctx, x, y, s, seed) => OUT.gem(ctx, x, y, s, ITEM, FROZEN, seed);
const lantern = (ctx, x, y, s, seed) => OUT.lantern(ctx, x, y, s, ITEM, FROZEN, seed);

/**
 * วาดห้องทั้งหมด
 *
 * ลำดับการวาดคือลำดับความลึกจริง ๆ: กำแพง → ของบนกำแพง → พื้น → พรม →
 * ของบนพื้น → โต๊ะสองฝั่ง → ของบนโต๊ะ
 * ตัวน้องถูกวาดทีหลังโดย drawRoom() ใน game.js จึงยืนอยู่หน้าพรมแต่หลังโต๊ะ
 */
export function drawRoomScene(ctx, p = ROOM) {
  ctx.save();
  ctx.beginPath();
  ctx.rect(0, 0, W, H);
  ctx.clip();

  // ── ผนังกับของที่ติดอยู่บนผนัง ──
  R.wall(ctx, W, FLOOR_Y, p);

  R.brushRack(ctx, 96, 34, 0.92, p, 3);
  R.shelfUnit(ctx, 232, FLOOR_Y - 4, 0.95, p, 11);
  R.archWindow(ctx, 480, 116, 1, p);
  R.pawSign(ctx, 480, 18, 1.1, p);
  R.shelfUnit(ctx, 728, FLOOR_Y - 4, 0.95, p, 23);
  R.featherHang(ctx, 812, 30, 1, p, 31);
  R.treasureMap(ctx, 876, 74, 0.95, p, 5);
  R.treasureMap(ctx, 928, 160, 0.8, p, 17);

  // เคาน์เตอร์เตี้ยพาดหลังห้อง เชื่อมตู้สองฝั่งเข้าหากัน
  // ถ้าไม่มี ตู้สองใบจะลอยอยู่คนละมุมโดยไม่มีอะไรผูกไว้ด้วยกัน
  ctx.fillStyle = p.woodLight;
  ctx.fillRect(0, FLOOR_Y - 16, W, 8);
  ctx.fillStyle = p.wood;
  ctx.fillRect(0, FLOOR_Y - 8, W, 8);
  ctx.strokeStyle = p.line;
  ctx.lineWidth = 2;
  ctx.beginPath();
  ctx.moveTo(0, FLOOR_Y - 16); ctx.lineTo(W, FLOOR_Y - 16);
  ctx.stroke();

  // หลอดด้ายวางบนเคาน์เตอร์ กระจายซ้ายขวาให้ไม่โล่ง
  for (const [sx, sd] of [[62, 2], [140, 7], [330, 13], [630, 19], [822, 29], [900, 37]]) {
    R.spool(ctx, sx, FLOOR_Y - 16, 0.85, p, sd);
  }
  for (const [mx, md] of [[392, 4], [572, 9]]) {
    R.mouseStill(ctx, mx, FLOOR_Y - 16, 0.7, p, md);
  }

  // ── พื้น ──
  R.floor(ctx, W, H, FLOOR_Y, p);

  // ชั้นบันไดขวดยา วางชิดผนังใต้หน้าต่างพอดี = จุดกึ่งกลางของฉาก
  // ถ่างขั้นบันไดออกให้ขวดยาโผล่พ้นตัวน้องทั้งสองข้าง
  // ตัวน้องกว้างราว 120 หน่วยและยืนกลางฉากพอดี ของที่แคบกว่านั้นจะถูกบังหมด
  R.potionSteps(ctx, 480, FLOOR_Y + 8, 1, p, potion);

  // พรมหัวใจ วางให้เท้าน้อง (ซึ่งอยู่ที่ GROUND_Y) ตกลงในผืนพอดี
  R.heartRug(ctx, 480, GROUND_Y + 14, 1, p);

  // หนูวิ่งเล่นบนพื้น สองตัวคนละฝั่งของพรม
  R.mouseStill(ctx, 372, GROUND_Y - 6, 0.85, p, 21);
  R.mouseStill(ctx, 596, GROUND_Y - 2, 0.9, p, 33);

  // ── โต๊ะสองฝั่ง อยู่หน้าสุดของฉาก ──
  // วางเยื้องออกนอกจอทั้งสองข้าง ห้องจึงดูกว้างกว่ากรอบภาพ ไม่ใช่กล่องปิด
  // ── ทำไมโต๊ะต้องยื่นออกนอกจอ แต่ไม่ใช่ยื่นจนหมด ──
  // ยื่นออกไปบ้างทำให้ห้องดูกว้างกว่ากรอบภาพ แต่ของเดิมวางไว้ที่ -46 กับ 1006
  // ซึ่งเหลือให้เห็นแค่เสี้ยวเดียว มุมล่างสองข้างเลยโล่งทั้งที่ควรเป็นจุดที่แน่นที่สุด
  drawBench(ctx, p, 78, 330, 330, 'left');
  drawBench(ctx, p, 882, 330, 330, 'right');

  // ตะกร้าไหมพรมกองที่พื้นมุมล่าง ปิดมุมที่เหลือของภาพ
  R.yarnBasket(ctx, 84, 414, 1.1, p, 41, yarn);
  R.yarnBasket(ctx, 878, 414, 1.1, p, 53, yarn);

  warmLight(ctx, p);

  ctx.restore();
}

/**
 * แสงในห้อง — เรืองอุ่นจากโคมไฟฝั่งขวา กับขอบมืดรอบภาพ
 *
 * ── ทำไมภาพนิ่งยังต้องมีแสง ──
 * ห้องที่สว่างเท่ากันทุกตารางนิ้วอ่านเป็น "ภาพวาดแบน" ไม่ใช่ "ห้อง"
 * แสงที่มีทิศทางคือสิ่งเดียวที่บอกว่ามีที่ว่างจริงอยู่ในนั้น
 * และขอบมืดยังทำหน้าที่ดันสายตาเข้าหากลางภาพ ซึ่งเป็นที่ที่น้องยืนอยู่พอดี
 *
 * เป็นไล่สีสองชั้น วาดทีเดียวจบ ไม่ได้ขยับตามเวลา ฉากนี้ยังเป็นภาพนิ่งเหมือนเดิม
 */
function warmLight(ctx, p) {
  const lamp = ctx.createRadialGradient(788, 300, 20, 788, 300, 300);
  lamp.addColorStop(0, p.glow);
  lamp.addColorStop(1, 'rgba(255,214,150,0)');
  ctx.fillStyle = lamp;
  ctx.fillRect(0, 0, W, H);

  const edge = ctx.createRadialGradient(W / 2, H * 0.46, H * 0.34, W / 2, H * 0.46, H * 1.05);
  edge.addColorStop(0, 'rgba(58,34,20,0)');
  edge.addColorStop(1, 'rgba(58,34,20,.42)');
  ctx.fillStyle = edge;
  ctx.fillRect(0, 0, W, H);
}

/**
 * โต๊ะหนึ่งตัวพร้อมของที่วางอยู่บนนั้น
 * แยกออกมาเพราะสองฝั่งใช้โครงเดียวกัน ต่างแค่ของที่วาง — ฝั่งซ้ายเป็นหม้อต้ม
 * ฝั่งขวาเป็นโคมไฟ ซึ่งเป็นจุดเข้มสุดกับจุดสว่างสุดของภาพ ถ่วงกันคนละมุม
 */
function drawBench(ctx, p, x, y, w, side) {
  R.table(ctx, x, y, w, 1, p);
  const top = y - 13;

  // ── ระยะเยื้องต้องอยู่ในครึ่งความกว้างของโต๊ะเสมอ ──
  // ค่าชุดเดิมเขียนไว้ตอนโต๊ะยังอยู่นอกจอ พอย้ายโต๊ะเข้ามาแล้วไม่ได้ตามแก้
  // ผลคือโหลกับเพชรไปลอยอยู่กลางอากาศข้างโต๊ะ ซึ่งเห็นชัดมากในภาพ
  // คิดจากขอบโต๊ะแทนการเขียนเลขตายตัว ย้ายโต๊ะอีกกี่ครั้งของก็ยังอยู่บนโต๊ะ
  const half = w / 2;
  const at = (u) => x + (side === 'left' ? u : -u) * half;

  if (side === 'left') R.cauldron(ctx, at(0.22), top, 1.05, p);
  else lantern(ctx, at(0.24), top, 1.25, 9);

  R.herbJar(ctx, at(0.62), top, 0.95, p, side === 'left' ? 7 : 19);
  gem(ctx, at(0.86), top - 6, 0.9, side === 'left' ? 12 : 34);
  gem(ctx, at(0.98), top - 4, 0.78, side === 'left' ? 26 : 44);
  R.mouseStill(ctx, at(0.44), top, 0.78, p, side === 'left' ? 15 : 25);

  // ลูกไหมพรมวางบนโต๊ะฝั่งริมจอ
  // เดิมเป็นตะกร้าที่ at(-0.66) ซึ่งคำนวณแล้วตกไปอยู่นอกจอทั้งสองข้าง = วาดทิ้งเปล่า ๆ
  // (ตะกร้าที่พื้นมุมล่างทำหน้าที่ปิดมุมอยู่แล้ว ตรงนี้ต้องการแค่ของเติมหน้าโต๊ะ)
  yarn(ctx, at(-0.3), top, 0.85, side === 'left' ? 61 : 71);
  yarn(ctx, at(-0.12), top, 0.7, side === 'left' ? 63 : 73);
}

export { ROOM } from './palette.js';
