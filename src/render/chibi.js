const hexA = (hex, a) => { const n = parseInt(hex.slice(1), 16); return `rgba(${(n >> 16) & 255},${(n >> 8) & 255},${n & 255},${a})`; };
/** ปื้นสีขอบนุ่ม (วงรี ไล่จางที่ขอบ) */
function softBlob(ctx, cx, cy, rx, ry, color, edge = 0.7, a = 1) {
  ctx.save();
  ctx.translate(cx, cy);
  ctx.scale(1, ry / rx);
  const g = ctx.createRadialGradient(0, 0, 0, 0, 0, rx);
  g.addColorStop(0, hexA(color, a));
  g.addColorStop(edge, hexA(color, a));
  g.addColorStop(1, hexA(color, 0));
  ctx.fillStyle = g;
  ctx.beginPath();
  ctx.arc(0, 0, rx, 0, Math.PI * 2);
  ctx.fill();
  ctx.restore();
}
/** ขอบในไล่เงาเข้มนิด ๆ ให้ตัวดูนูน (เหมือนพ่นสีตัวโต) */
function rimShade(ctx, path, look, w = 30) {
  ctx.save();
  ctx.clip(path);
  ctx.strokeStyle = look.rim;
  ctx.lineJoin = 'round';
  // ไล่ 14 ชั้นบาง ๆ (กว้าง → แคบ) ซ้อนกันเป็นเงาเนียน ไม่เป็นวงขั้นบันได
  for (let i = 0; i < 14; i++) { ctx.globalAlpha = 0.036; ctx.lineWidth = w * (1 - i / 14); ctx.stroke(path); }
  ctx.restore();
}
/** ลายขีดส้มเข้มขอบนุ่ม */
function stripes(ctx, look, list, w = 6) {
  ctx.save();
  ctx.strokeStyle = look.stripe;
  ctx.lineCap = 'round';
  for (const pts of list) {
    for (const [k, a] of [[1.6, 0.18], [1, 0.42]]) { ctx.globalAlpha = a * (look.stripeA ?? 1); ctx.lineWidth = w * k; ctx.stroke(curve(pts)); }
  }
  ctx.restore();
}
/** เส้นขาวเรียวปลายแหลม (แถบขาวกลางหลัง/หางวิลาศ) — กว้างสุด w ตรงกลาง */
function taperLine(ctx, pts, w, col) {
  const P = resample(pts, 6), n = P.length, L = [], R = [];
  for (let i = 0; i < n; i++) {
    const a = P[Math.max(0, i - 1)], b = P[Math.min(n - 1, i + 1)];
    const dx = b[0] - a[0], dy = b[1] - a[1], l = Math.hypot(dx, dy) || 1;
    const hw = (w / 2) * Math.sin(Math.PI * Math.min(1, Math.max(0, i / (n - 1)))) ** 0.6;
    L.push([P[i][0] - (dy / l) * hw, P[i][1] + (dx / l) * hw]);
    R.push([P[i][0] + (dy / l) * hw, P[i][1] - (dx / l) * hw]);
  }
  ctx.fillStyle = col;
  ctx.fill(spline(new Path2D(), [...L, ...R.reverse()], true));
}
