  rg.addColorStop(1, 'rgba(90,50,8,.5)');
  ctx.fillStyle = rg;
  ctx.fillRect(-r - 6, -r - 6, (r + 6) * 2, (r + 6) * 2);
  const px = cx - o * r * 0.06, py = cy + 3, pr = r * 0.78;   // ตาดำโต (เด็ก — ตัวโต 0.52 · ผู้ใช้ 14 พ.ย. ขอโตขึ้นอีก)
  ctx.fillStyle = C.ring;
