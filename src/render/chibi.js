/** t (เฟรม 60fps) → { walk4, walkPhase } ส่งต่อเข้า drawChibi ได้เลย */
export function chibiWalk4At(t) {
  const ph = (((t / CHIBI_WALK4_BEAT) % 4) + 4) % 4;
  return { walk4: Math.floor(ph), walkPhase: ph };
}
/** หมุนชุดจุดรอบจุด c (เรเดียน) */
function rotAbout(pts, c, a) {
  if (!a) return pts;
  const cs = Math.cos(a), sn = Math.sin(a);
  return pts.map(([x, y]) => [c[0] + (x - c[0]) * cs - (y - c[1]) * sn, c[1] + (x - c[0]) * sn + (y - c[1]) * cs]);
}
/** ท่าจังหวะ b (0..4 วนลูป) · ทศนิยม = ผสมรูปตัว/หางไปจังหวะถัดไป (ปุ่ม "ผสมระหว่างจังหวะ") · เส้นใน/เท้า ใช้จังหวะที่ใกล้กว่า */
function walk4Pose(b) {
  const i = ((Math.floor(b) % 4) + 4) % 4, m = b - Math.floor(b), A = WALK4[i], B = WALK4[(i + 1) % 4];
  const near = m < 0.5 ? A : B;
  const lerp = (P, Q) => P.map((p, k) => [p[0] + (Q[k][0] - p[0]) * m, p[1] + (Q[k][1] - p[1]) * m]);
  const ends = (mid) => [W4_TOP[W4_TOP.length - 1], ...mid, W4_ARM_R[0]];
  const mid = m ? lerp(arcSample(ends(A.mid), 44), arcSample(ends(B.mid), 44)).slice(1, -1) : A.mid;
  const tail = m ? lerp(arcSample(A.tail, 12), arcSample(B.tail, 12)) : A.tail;
  return { label: A.label, body: [...W4_TOP, ...mid, ...W4_ARM_R], lines: near.lines, feet: near.feet, tail };
}

function walkPose(t) {
  const ph = (t / WALK_T) * Math.PI * 2;
  const bob = 2.6 * (1 - Math.cos(2 * ph)) / 2;                  // ลอยสองทีต่อรอบ (ตอนขากางสุด = ต่ำสุด)
  const legs = WALK_LEGS.map(([hx, off, far]) => {
    const a = ph + off, sw = Math.sin(a);
    const lift = Math.max(0, Math.cos(a)) * 9;                     // ขาที่ก้าวไปหน้า (ลอย) ยกเท้า
    const hip = [hx, -32 + bob];
    const foot = [hx - sw * LEG_L * Math.sin(LEG_SWING), bob - lift + bob * 0];
    foot[1] = Math.min(0, -lift) + 0;                              // เท้าแตะพื้นจริง (y 0 ของพื้น) ยกเฉพาะตอนก้าว
    const knee = [(hip[0] + foot[0]) / 2 - lift * 0.35, (hip[1] + foot[1]) / 2];
    return { pts: [hip, knee, foot], foot, far };
  });
  return {
    ph, bob, legs,
    arm: -0.3 * Math.sin(ph),                                      // แขนแกว่งสวนขาหน้าใกล้
    headBob: 2.6 * (1 - Math.cos(2 * ph - 0.6)) / 2,               // หัวช้ากว่าตัวนิด
    ear: 0.05 * Math.sin(2 * ph),
  };
}


