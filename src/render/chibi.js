/** ท่อนล่างเปิด (จากซอกแขนหน้าถึงแขนหลัง) → n จุดห่างเท่ากันตามเส้นโค้งจริง — ใช้ผสมระหว่างจังหวะ */
function arcSample(pts, n) {
  const d = resample(pts, 8), acc = [0];
  for (let i = 1; i < d.length; i++) acc.push(acc[i - 1] + Math.hypot(d[i][0] - d[i - 1][0], d[i][1] - d[i - 1][1]));
  const L = acc[acc.length - 1], out = [];
  for (let k = 0, j = 1; k < n; k++) {
    const want = (L * k) / (n - 1);
    while (j < d.length - 1 && acc[j] < want) j++;
    const u = (want - acc[j - 1]) / (acc[j] - acc[j - 1] || 1);
    out.push([d[j - 1][0] + (d[j][0] - d[j - 1][0]) * u, d[j - 1][1] + (d[j][1] - d[j - 1][1]) * u]);
  }
  return out;
}
/**
 * การเคลื่อนไหวทั้งตัวตอนเดิน 4 จังหวะ (ผู้ใช้ 14 พ.ย.: "ใส่อนิเมชั่นตอนเดินทั้งตัว จังหวะขึ้นลงด้วย")
 * ph = จังหวะต่อเนื่อง (0..4) · ยอดสูงสุดกลางจังหวะ Up (0.5 · 2.5) ต่ำสุดกลางจังหวะ Down (1.5 · 3.5) = ขึ้นลงสองทีต่อรอบ
 * lift = ตัวลอยขึ้น · stretch = ตัวยืด (+) ยุบ (−) ที่เท้า · headLag = หัวตามตัวช้ากว่านิด (ไม่โยกเกินตัว)
 * tilt = เอียงไปทางข้างที่ก้าว (รอบละ 4 จังหวะ) · ear = หูกระพือตามแรงขึ้นลง · tail = หางสะบัดตามก้าว
 */
export function chibiWalk4Motion(ph) {
  const u = Math.PI * (ph - 0.5);
  const rise = 0.5 + 0.5 * Math.cos(u);
  const riseLag = 0.5 + 0.5 * Math.cos(u - 0.6);
  return {
    lift: W4_BOB * rise,
    stretch: 0.024 * (rise * 2 - 1),
    headLag: W4_BOB * 0.22 * (riseLag - rise),
    tilt: 0.022 * Math.sin((Math.PI / 2) * (ph - 0.5)),
    ear: 0.09 * Math.sin(u - 1.3),
    tail: 0.07 * Math.sin(u - 0.9) + 0.05 * Math.sin((Math.PI / 2) * (ph - 0.5) - 0.8),
  };
}
const W4_BOB = 4.5;   // ตัวลอยขึ้นสูงสุดตอน Up (หน่วยชีท)
