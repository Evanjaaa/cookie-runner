/**
 * ตาแผ่นม่านตา (ขาวมณี / ส้มซ่า / เสือน้อย — ผู้ใช้ 14 พ.ย.: ลงสีแมวเด็ก ตาโตแบ๊ว ขนตาตามตัวโต)
 * พื้นตา (base: เสี้ยวเหลืองมะนาว / ตาขาวครีม / ทองสด) → แผ่นม่านตาวงใหญ่เยื้องขึ้นเข้าหาจมูก (disk) → ตาดำ (pupil)
 * เหลือพื้นตาเป็นเสี้ยวด้านล่าง-นอก (แบบตัวโตทั้งสามตัว) · ประกายวงใหญ่บนซ้าย + จุดเล็กล่างขวา · เด็ก = ตาดำโตกว่าตัวโต
 * ต่อด้วยไลเนอร์บนของตัวนั้น (D.lid) — ตัวผู้ทั้งสามตัว ไม่มีขนตาแยก
 */
function discEye(ctx, rx, h, o, D) {
  ctx.save();
  ctx.scale(rx / 49, h / 49);
  const r = 49, E = new Path2D();
  E.ellipse(0, 0, r, r, 0, 0, Math.PI * 2);
  ctx.save();
  ctx.clip(E);
  const g = ctx.createLinearGradient(0, -r, 0, r);
  D.base.forEach((c, i) => g.addColorStop(i / Math.max(1, D.base.length - 1), c));
  ctx.fillStyle = g;
  ctx.fillRect(-r, -r, r * 2, r * 2);
  const dx = -o * r * D.off, dy = -r * D.off, dr = r * D.disk;
  const dg = ctx.createLinearGradient(0, dy - dr, 0, dy + dr);
  D.diskCol.forEach((c, i) => dg.addColorStop(i / Math.max(1, D.diskCol.length - 1), c));
  ctx.fillStyle = dg;
  ctx.beginPath(); ctx.arc(dx, dy, dr, 0, Math.PI * 2); ctx.fill();
  if (D.edge) { ctx.strokeStyle = D.edge; ctx.lineWidth = 3; ctx.stroke(); }
  if (D.glow) softBlob(ctx, dx + o * dr * 0.1, dy + dr * 0.62, dr * 0.6, dr * 0.3, D.glow, 0.2, 0.55);
  const px = dx, py = dy + r * (D.pdy || 0), pr = r * D.pupil;
  ctx.fillStyle = D.pupilCol;
  ctx.beginPath(); ctx.arc(px, py, pr, 0, Math.PI * 2); ctx.fill();
  ctx.fillStyle = '#FFFFFF';
  ctx.beginPath(); ctx.arc(dx - dr * 0.36, dy - dr * 0.38, r * 0.2, 0, Math.PI * 2); ctx.fill();
  ctx.globalAlpha = 0.92;
  ctx.beginPath(); ctx.arc(dx + dr * 0.4, dy + dr * 0.36, r * 0.085, 0, Math.PI * 2); ctx.fill();
  ctx.globalAlpha = 1;
  ctx.restore();
  ctx.strokeStyle = D.rim || '#3A2218';
  ctx.lineWidth = D.rimW || 3;
  ctx.stroke(E);
  // ไลเนอร์บน (พอร์ตจาก drawManeeLashes / drawSomsaLashes / drawSueaLashes)
  const L = D.lid, P = (a, rr) => [o * Math.cos(a) * rr, Math.sin(a) * rr];
  const Nn = (a) => [o * Math.cos(a), Math.sin(a)];
  const n = 40, lid = new Path2D(), outer = [];
  for (let i = 0; i <= n; i++) {
    const u = i / n, a = L.a0 + (L.a1 - L.a0) * u, th = L.th(u);
    const b = P(a, r - 1.4), nn = Nn(a);
    if (!i) lid.moveTo(...b); else lid.lineTo(...b);
    outer.push([b[0] + nn[0] * th, b[1] + nn[1] * th]);
  }
  if (L.tip) {
    const e = P(L.a1 + L.tip.da, r - 1.4), [nx, ny] = Nn(L.a1);
    const tip = [e[0] + o * L.tip.dx, e[1] - L.tip.dy];
    lid.quadraticCurveTo(...P(L.a1 + L.tip.da / 2, r - 1.4), ...e);
    lid.quadraticCurveTo(e[0] + o * L.tip.dx * 0.66, e[1] - L.tip.dy * 0.3, ...tip);
    lid.quadraticCurveTo(outer[n][0] + o * 2 + nx * 2, outer[n][1] + ny * 2, ...outer[n]);
    for (let i = n - 1; i >= 0; i--) lid.lineTo(...outer[i]);
  } else for (let i = n; i >= 0; i--) lid.lineTo(...outer[i]);
  lid.closePath();
  ctx.fillStyle = L.ink;
  ctx.fill(lid);
  ctx.restore();
}

