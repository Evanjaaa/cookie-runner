  ctx.beginPath(); ctx.arc(px, py, pr + 4, 0, Math.PI * 2); ctx.fill();
  ctx.globalAlpha = 1;
  const pg = ctx.createRadialGradient(px, py + pr * 0.45, pr * 0.1, px, py, pr);
  pg.addColorStop(0, C.pupilIn);
  pg.addColorStop(1, C.pupilOut);
  ctx.fillStyle = pg;
  ctx.beginPath(); ctx.arc(px, py, pr, 0, Math.PI * 2); ctx.fill();
  const gl = ctx.createRadialGradient(cx, cy + r * 0.62, 0, cx, cy + r * 0.62, r * 0.7);
  gl.addColorStop(0, 'rgba(255,196,80,.36)');
  gl.addColorStop(1, 'rgba(255,196,80,0)');
  ctx.fillStyle = gl;
  ctx.fillRect(-r - 6, -r - 6, (r + 6) * 2, (r + 6) * 2);
