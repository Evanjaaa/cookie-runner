// ── ทำไมแยกเป็นไฟล์ของตัวเอง ──
// การเดินนี้คร่อมรอยตัดระหว่างสองฉาก ถ้าแต่ละฉากคิดตำแหน่งเอง ตรงรอยตัดจะเห็นเจ้าของ
// กระตุก เร่ง หรือชะลอ (เคยเป็นแบบนั้นจริง) — ให้ทั้งสองฉากถามตำแหน่งจากที่เดียว
// ด้วย "เวลาของเพลง" ตรง ๆ การเดินจึงต่อเนื่องความเร็วเท่ากันตลอดทางไม่ว่าจะตัดภาพตรงไหน
//
// เวลาทุกค่าในไฟล์นี้เป็นเวลาของเพลง (วินาทีนับจาก 0:00) ไม่ใช่เวลาในฉาก
// ─────────────────────────────────────────────────────────────
import { HOME } from './home.js';

/** ความเร็วเดินของเจ้าของ = ความเร็วที่น้องเดินตาม (หน่วยโลก/วินาที) — เท่ากันตลอดทาง ไม่มีช่วงช้า */
export const PACE = 180;

export const WALK = {
  bell: 30.3,                          // กริ่งหน้าบ้านดัง (น้องกินข้าวจนถึงตอนนี้)
  ownerGo: 30.6,                       // เจ้าของออกเดิน
  ownerFrom: HOME.bowl.x + 110,        // ยืนหน้าเคาน์เตอร์ ขวาของชาม
  stopX: (HOME.door.x0 + HOME.door.x1) / 2 + 20,   // หยุดยืนหน้าประตู
  catStand: 31.3,                      // น้องลุกจากท่านั่ง (ตอนเจ้าของกำลังเดินผ่านหน้า)
  catGo: 31.75,                        // น้องออกเดินตาม
  catAccel: 0.5,                       // ก้าวแรก ๆ ค่อย ๆ เร่งจากหยุดนิ่งถึงความเร็วเดิน ใช้เวลาเท่านี้
  catFrom: HOME.bowl.x - 72,           // ที่นั่งข้างชาม
  heel: 34,                            // น้องชนส้นเท้า = ห่างจากกลางขาเจ้าของเท่านี้
};

/** เจ้าของหยุดหน้าประตูเมื่อไร */
export const OWNER_STOP = WALK.ownerGo + (WALK.ownerFrom - WALK.stopX) / PACE;
/** น้องชนส้นเท้าเมื่อไร — เดินตามความเร็วเดียวกัน เจ้าของหยุดแล้วน้องยังเดินต่อจนชน
 *  (ช่วงเร่งตัวตอนออกเดินเสียเวลาไปครึ่งหนึ่งของ catAccel เมื่อเทียบกับการเดินเต็มความเร็วตั้งแต่ต้น) */
export const CAT_BUMP = WALK.catGo + (WALK.catFrom - (WALK.stopX + WALK.heel)) / PACE + WALK.catAccel / 2;

export function ownerWalkX(g) {
  if (g < WALK.ownerGo) return WALK.ownerFrom;
  return Math.max(WALK.stopX, WALK.ownerFrom - PACE * (g - WALK.ownerGo));
}

export function catWalkX(g) {
  if (g < WALK.catGo) return WALK.catFrom;
  const d = g - WALK.catGo, A = WALK.catAccel;
  // เร่งสม่ำเสมอจาก 0 ถึง PACE ในช่วง A วินาทีแรก แล้วเดินคงที่ — ไม่มีการกระโดดจากนั่งเป็นวิ่งเต็มสปีด
  const run = d < A ? (PACE * d * d) / (2 * A) : PACE * (d - A / 2);
  return Math.max(WALK.stopX + WALK.heel, WALK.catFrom - run);
}

/** จังหวะก้าว — คิดจากระยะที่เดินมาจริง ขาจึงไม่ไถลบนพื้น และต่อกันตรงรอยตัดฉาก */
export const ownerStep = (x) => (WALK.ownerFrom - x) / 190;
export const catStep = (x) => (WALK.catFrom - x) * 1.4;
