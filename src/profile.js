import { loadPref, savePref } from './storage.js';

const KEY = 'status';

/** ยาวได้กี่ตัวอักษร และขึ้นบรรทัดใหม่ได้กี่บรรทัด */
export const STATUS_MAX = 100;
export const STATUS_LINES = 3;

/**
 * ตัดข้อความให้อยู่ในกติกา — เรียกทั้งตอนบันทึกและตอนอ่านกลับ
 *
 * ── ทำไมนับด้วย Array.from ไม่ใช่ .length ──
 * อีโมจิหนึ่งตัวยาวสองหน่วยใน .length การตัดด้วย slice ตรง ๆ จึงตัดกลางอีโมจิได้
 * แล้วเหลือครึ่งตัวที่แสดงผลไม่ออกค้างไว้ Array.from ตัดตามจุดโค้ด
 * ซึ่งไม่แยกคู่แทนออกจากกัน
 */
export function cleanStatus(raw) {
  if (typeof raw !== 'string') return '';
  const lines = raw
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((l) => l.replace(/[ \t]+$/, ''))
    .slice(0, STATUS_LINES);
  // ตัดบรรทัดว่างหัวท้ายทิ้ง แต่เก็บบรรทัดว่างที่อยู่ตรงกลางไว้ตามที่พิมพ์
  while (lines.length && !lines[0].trim()) lines.shift();
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
  const text = lines.join('\n');
  const chars = Array.from(text);
  return chars.length > STATUS_MAX ? chars.slice(0, STATUS_MAX).join('') : text;
}

/** นับความยาวแบบเดียวกับที่ cleanStatus ใช้ — ตัวนับใต้กล่องพิมพ์ต้องตรงกับของจริง */
export function statusLength(text) {
  return Array.from(typeof text === 'string' ? text : '').length;
}

export function loadStatus() {
  return cleanStatus(loadPref(KEY, ''));
}

/** คืนข้อความที่บันทึกจริง ซึ่งอาจสั้นกว่าที่ส่งเข้ามาถ้ายาวเกินกติกา */
export function saveStatus(text) {
  const out = cleanStatus(text);
  savePref(KEY, out);
  return out;
}
