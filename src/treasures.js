/** ตัวคูณฤทธิ์ตามขั้นที่ตีบวกไว้ — ขั้น 0 คือ 1 เท่า (ไม่ตีบวกก็ใช้ได้ปกติ) */
export function levelMult(level) {
  return 1 + UPGRADE.perLevel * Math.max(0, Math.min(UPGRADE.maxLevel, level | 0));
}

