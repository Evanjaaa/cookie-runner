/**
 * ฤทธิ์จริงหลังคูณขั้นตีบวกแล้ว
 *
 * แยกเป็นฟังก์ชันเดียวที่ทุกที่เรียกใช้ ทั้งหน้าจอที่โชว์ตัวเลขและตัวรันในเกม
 * ถ้าปล่อยให้ต่างคนต่างคูณเอง วันหนึ่งจะมีที่ลืมคูณแล้วเลขบนจอไม่ตรงกับที่ได้จริง
 */
export function effectValue(t, level) {
  const m = levelMult(level);
  const e = t.effect;
  if (e.type === 'score') return Math.round(e.amount * m);
  if (e.type === 'rate') return e.amount * m;          // 0.1 → 0.15 ที่ขั้น 5
  if (e.type === 'guard') return Math.round(e.frames * m);
  if (e.type === 'spawn') return Math.round(e.count * m);
  if (e.type === 'jump') return Math.round(e.cooldown / m);   // ยิ่งขั้นสูง คูลดาวน์ยิ่งสั้น
  return 0;
}

/** ข้อความสรุปฤทธิ์ที่เอาไปโชว์บนการ์ดได้เลย */
export function effectText(t, level) {
  const v = effectValue(t, level);
  const e = t.effect;
  if (e.type === 'score') return '+' + v.toLocaleString('en-US') + ' คะแนน';
  if (e.type === 'rate') return 'คะแนนของกิน +' + Math.round(v * 100) + '%';
  if (e.type === 'guard') return 'กันตาย 1 ครั้ง + โล่ ' + (v / 60).toFixed(1) + ' วิ';
  if (e.type === 'spawn') return 'เสกของกิน ' + v + ' ชิ้น';
  if (e.type === 'jump') return 'กระโดดเพิ่ม 1 ครั้ง (รอ ' + (v / 60).toFixed(0) + ' วิ)';
  return '';
}

/** เงื่อนไขที่ทำให้ฤทธิ์ทำงาน เขียนเป็นภาษาคน */
export function triggerText(t) {
  const g = t.trigger;
  if (g.type === 'time') return 'ทุก ' + Math.round(g.every / 60) + ' วินาที';
  if (g.type === 'treats') return 'เก็บของกินครบ ' + g.every + ' ชิ้น';
  if (g.type === 'combo') return 'เก็บติดกัน ' + g.every + ' ชิ้นไม่พลาด';
  if (g.type === 'air') return 'เก็บกลางอากาศครบ ' + g.every + ' ชิ้น';
  if (g.type === 'hit') return 'ตอนโดนชนครั้งแรก';
  return 'ทำงานตลอดเวลา';
}
