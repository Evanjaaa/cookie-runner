import { loadPref, savePref } from './storage.js';

/** กี่วันต่อหนึ่งรอบ — เปลี่ยนตัวเลขนี้ต้องเพิ่ม/ลดของในตาราง DAYS ให้ครบด้วย */
export const CYCLE = 7;

/**
 * ของรางวัลของแต่ละวัน (วันที่ 1 อยู่ช่องแรก)
 *
 * สลับทอง/เพชรวันเว้นวัน และเพิ่มขึ้นทุกสองวัน วันที่ 7 ได้ทั้งคู่ก้อนใหญ่
 * คนที่มาต่อเนื่องจึงเห็น "ของวันพรุ่งนี้ใหญ่กว่าวันนี้" ตลอดทั้งรอบ
 *
 * เทียบกับราคาจริงในเกม: หมุนตู้ชุด 1 ครั้ง = 5,000 ทอง / เปิดหีบสมบัติ 1 ครั้ง = 150 เพชร
 * ครบรอบได้ 16,000 ทอง + 1,650 เพชร ≈ หมุนตู้ชุดสามครั้ง + เปิดหีบสิบเอ็ดครั้ง
 *
 * big: true = การ์ดใบใหญ่เต็มแถวในหน้าเช็คอิน (ใช้กับวันสุดท้ายของรอบ)
 */
export const DAYS = [
  { gold: 1000 },
  { gems: 150 },
  { gold: 3000 },
  { gems: 300 },
  { gold: 5000 },
  { gems: 500 },
  { gold: 7000, gems: 700, big: true, note: 'ครบรอบเจ็ดวัน น้องดีใจมาก!' },
];

/** ของรางวัลของวันที่ n (1..7) */
export function rewardOfDay(n) {
  return DAYS[(n - 1 + CYCLE) % CYCLE];
}

// ── วันนี้คือวันอะไร ────────────────────────────────────────
//
// ใช้วันตามเวลาเครื่อง ไม่ใช่ UTC — คนเล่นคิดเป็น "วันของตัวเอง" เสมอ
// ถ้าใช้ UTC คนไทยที่เล่นตอนหกโมงเย็นจะข้ามวันตอนตีห้าของวันถัดไป ซึ่งงงมาก
// เก็บเป็นข้อความ YYYY-MM-DD เพราะเทียบเท่ากันตรง ๆ ได้โดยไม่ต้องแปลงเวลา
// และไม่เพี้ยนตอนเครื่องเปลี่ยนเขตเวลาระหว่างวัน (ค่าที่เก็บไว้ยังอ่านออกเหมือนเดิม)

export function todayKey(d = new Date()) {
  const p = (n) => String(n).padStart(2, '0');
  return d.getFullYear() + '-' + p(d.getMonth() + 1) + '-' + p(d.getDate());
}

const PREF = 'daily';

/** ค่าที่บันทึกไว้ { day, last, cycles } — day คือวันที่ "รับไปแล้วล่าสุด" */
function load() {
  const raw = loadPref(PREF, null);
  if (!raw || typeof raw !== 'object') return { day: 0, last: '', cycles: 0 };
  const day = Math.floor(Number(raw.day) || 0);
  return {
    day: day >= 0 && day <= CYCLE ? day : 0,
    last: typeof raw.last === 'string' ? raw.last : '',
    cycles: Math.max(0, Math.floor(Number(raw.cycles) || 0)),
  };
}

/**
 * สถานะของวันนี้ที่หน้าจอต้องใช้ทั้งหมด
 *   day      วันที่รับไปแล้วล่าสุดในรอบนี้ (0 = ยังไม่เคยรับเลย)
 *   next     วันที่จะได้ถ้ากดรับตอนนี้ (1..7)
 *   ready    วันนี้ยังไม่ได้รับ = กดได้
 *   cycles   ครบรอบเจ็ดวันไปแล้วกี่รอบ
 */
export function dayState() {
  const s = load();
  const ready = s.last !== todayKey();
  // รับครบเจ็ดวันแล้วรอบใหม่เริ่มที่วันที่ 1 เสมอ
  const next = ready ? (s.day % CYCLE) + 1 : s.day;
  return { day: s.day, next, ready, cycles: s.cycles, last: s.last };
}

/**
 * กดรับของวันนี้
 * คืน { n, reward } ถ้ารับได้จริง หรือ null ถ้าวันนี้รับไปแล้ว
 */
export function claimToday() {
  const st = dayState();
  if (!st.ready) return null;

  const n = st.next;
  const done = n >= CYCLE;
  savePref(PREF, {
    day: done ? 0 : n,            // ครบรอบแล้วเริ่มนับใหม่จากศูนย์
    last: todayKey(),
    cycles: st.cycles + (done ? 1 : 0),
  });
  return { n, reward: rewardOfDay(n), finishedCycle: done };
}
