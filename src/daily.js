// หายไปสองวันด้วยการล้างของที่สะสมมาหกวันทำให้คนเลิกเล่นมากกว่าทำให้กลับมา
// จึงเลือกแบบใจดี: หายไปนานแค่ไหนก็กลับมารับต่อจากวันเดิมได้เลย
