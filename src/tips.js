const PREF = 'tipsSeen';

export function tipSeen(id) {
  const seen = loadPref(PREF, []);
  return Array.isArray(seen) && seen.includes(id);
}

export function markTip(id) {
  const seen = loadPref(PREF, []);
  const list = Array.isArray(seen) ? seen : [];
  if (!list.includes(id)) {
    list.push(id);
    savePref(PREF, list);
  }
}
