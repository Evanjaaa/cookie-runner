// ── ฟังก์ชันจังหวะ (easing) ──────────────────────────────────
// ห้ามเคลื่อนเป็นเส้นตรง — ของที่เร่ง/ชะลอเป็นเส้นตรงอ่านเป็นเครื่องจักร ไม่ใช่สัตว์
export const E = {
  io: (u) => u * u * (3 - 2 * u),               // ค่อย ๆ ออก ค่อย ๆ เข้า
  out: (u) => 1 - (1 - u) ** 3,                  // พุ่งออกเร็ว ชะลอเข้าเป้า
  in: (u) => u * u * u,                          // ค่อย ๆ เร่ง (ตกลงพื้น)
  // เลยเป้าไปนิดแล้วเด้งกลับ (overshoot) — ใช้กับทุกการ "ยก/ยื่น" ที่ต้องมีแรง
  back: (u) => { const c = 1.9, v = u - 1; return 1 + (c + 1) * v * v * v + c * v * v; },
};

/**
 * ค่า ณ เวลา t จากจุดคีย์ [[เฟรม, ค่า, easing?], ...] (เรียงตามเฟรม)
 * easing ของแต่ละช่วงเป็นของ "คีย์ปลายทาง" — อ่านง่ายว่า "ไปถึงค่านี้ด้วยท่าแบบไหน"
 */
export function track(t, keys) {
  if (t <= keys[0][0]) return keys[0][1];
  for (let i = 1; i < keys.length; i++) {
    const [f1, v1, e = E.io] = keys[i];
    if (t <= f1) {
      const [f0, v0] = keys[i - 1];
      const u = f1 === f0 ? 1 : (t - f0) / (f1 - f0);
      return v0 + (v1 - v0) * e(u);
    }
  }
  return keys[keys.length - 1][1];
}

/** ซอง 0→1→0: ขึ้นช่วง a-b ค้าง b-c ลงช่วง c-d */
export function env(t, a, b, c, d) {
  if (t <= a || t >= d) return 0;
  if (t < b) return E.io((t - a) / (b - a));
  if (t > c) return E.io((d - t) / (d - c));
  return 1;
}

/**
 * สปริงหน่วงหลังจุดหนึ่ง — ใช้กับปลายหางที่สะบัดแล้วแกว่งค้างจนนิ่ง (follow through)
 * ก่อน t0 คืน v0 ตรง ๆ
 */
function spring(t, t0, v0, freq = 0.32, damp = 0.075) {
  if (t < t0) return v0;
  const d = t - t0;
  return v0 * Math.exp(-damp * d) * Math.cos(freq * d);
}

