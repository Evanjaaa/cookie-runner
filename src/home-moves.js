      sy: -heavy * 0.06 * curl + jolt * 0.08 + stretch * 0.06,
      ear: 0.85 * curl + Math.abs(rockLag) * 0.15 * curl,
      tilt: -rockLag * 0.12 * curl,
      shut: t > 24 && t < 156 ? 1 : 0,
      mood: t < 16 ? 'hurt' : '',
      // หางม้วนเข้าหาตัว แล้วแกว่งสวนแรงโยก
