/**
 * สุ่มท่าถัดไป — ไม่ซ้ำท่าล่าสุด
 * สุ่มจริงดีกว่าเรียงวน เพราะผู้เล่นแตะแล้วเดาไม่ได้ว่าจะได้อะไร (= น้องมีชีวิต)
 * แต่ห้ามซ้ำติดกัน เพราะท่าเดิมสองรอบอ่านเป็น "แตะแล้วไม่มีอะไรเกิดขึ้น"
 */
export function pickMove(lastId) {
  const pool = HOME_MOVES.filter((m) => m.id !== lastId);
  return pool[Math.floor(Math.random() * pool.length)];
}

/**
 * ผสมรูปร่างสองก้อน — ใช้ตอนเริ่มท่าจากท่าที่ค้างอยู่ (นั่ง/หมอบของท่าว่าง)
 * ตัวเลขไล่ค่าตรง ๆ ส่วนอารมณ์หน้า (ข้อความ) สลับตอนครึ่งทาง
 */
export function mixShape(a, b, u) {
  const out = {};
  for (const key of new Set([...Object.keys(a), ...Object.keys(b)])) {
    const va = a[key], vb = b[key];
    if (typeof va === 'string' || typeof vb === 'string') out[key] = u < 0.5 ? (va || '') : (vb || '');
    else out[key] = (va || 0) * (1 - u) + (vb || 0) * u;
  }
  return out;
}

/** คูณทุกช่องตัวเลขด้วย k — ท่าว่างที่เข้าไม่เต็ม เอามาเป็นจุดตั้งต้นของการผสม */
export function scaleShape(shape, k) {
  const out = {};
  for (const [key, v] of Object.entries(shape)) out[key] = typeof v === 'number' ? v * k : v;
  return out;
}
