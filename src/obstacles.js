/** ทะเบียนทั้งหมด: id → { id, stage, slot, type, difficulty, name, note, w, h, top? } */
export const PROP_OBSTACLES = {};
for (const [stage, set] of Object.entries(STAGE_SETS)) {
  SLOT_ORDER.forEach((slot, i) => {
    const s = SLOTS[slot];
    const n = String((i % 3) + 1).padStart(2, '0');
    const id = `${set.prefix}_Obstacle_${TYPE_NAME[s.type]}_${n}`;
    const [name, note] = set.names[i];
    PROP_OBSTACLES[id] = {
      id, stage, slot, type: s.type, difficulty: s.difficulty, name, note,
      w: s.w,
      h: s.type === 'crouch' ? CROUCH_BOTTOM - s.top : s.h,
      top: s.type === 'crouch' ? s.top : null,
    };
  });
}

/** รายการตามลำดับการแสดงผล (ด่าน → กระโดด → สองชั้น → หมอบ) */
export const PROP_LIST = Object.values(PROP_OBSTACLES);

/** ชิ้นนี้ต้อง "หมอบลอด" ไหม — ใช้แทนการเช็ค kind === 'bar' ทุกที่ */
export function isLowObstacle(o) {
  return o.kind === 'bar' || !!o.low;
}
