/** ด่านที่ผ่านแล้วในเส้นทางสัปดาห์นี้ (0 = ยังไม่ผ่านเลย — ด่าน 1 คือด่านปัจจุบัน) · ยังไม่มีโหมดจริง จึงเป็น 0 เสมอ */
