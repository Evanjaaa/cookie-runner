const MONTHS = ['ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.', 'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.'];
const thDate = (iso) => { const [y, m, d] = iso.split('-').map(Number); return `${d} ${MONTHS[m - 1]} ${String(y + 543).slice(-2)}`; };

/** สัปดาห์ที่ครอบวันนี้ (ยังไม่ถึงสัปดาห์แรก = สัปดาห์แรก · เลยสัปดาห์สุดท้าย = สัปดาห์สุดท้าย) */
export function currentWeek(now = new Date()) {
  const day = now.toISOString().slice(0, 10);
  const w = WEEKS.find((x) => day >= x.from && day <= x.to) || (day < WEEKS[0].from ? WEEKS[0] : WEEKS[WEEKS.length - 1]);
  return { ...w, range: `${thDate(w.from)} - ${thDate(w.to)}` };
}
