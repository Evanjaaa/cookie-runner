// จุดเข้าโปรแกรมตัวจริง — index.html ชี้มาที่ไฟล์นี้ ไม่ใช่ main.js
//
// ทำไมต้องมีชั้นนี้: โมดูลของเกมอ่าน localStorage ตั้งแต่ตอนถูก import
// (เช่น skins.js หยิบสีขนที่เลือกไว้, gacha.js หยิบจำนวนทอง) ซึ่งใน ES module
// การ import ถูกยกขึ้นไปทำงานก่อนโค้ดบรรทัดแรกเสมอ
//
// ถ้าดึงข้อมูลจากคลาวด์ใน main.js จะสายเกินไป — เกมอ่านค่าเก่าไปแล้ว
// จึงต้องดึงให้เสร็จก่อน แล้วค่อย import ตัวเกมแบบไดนามิก
//
// ผลพลอยได้: ถ้าไม่ได้ตั้งคีย์ Supabase ไฟล์นี้แทบไม่ทำอะไรเลย
// ข้ามไปโหลดเกมทันที เกมจึงยังเล่นได้เหมือนก่อนมีระบบคลาวด์ทุกประการ
// ─────────────────────────────────────────────────────────────
import { cloudReady } from './net/cloud.js';

async function boot() {
  if (cloudReady) {
    try {
      const { connect } = await import('./net/sync.js');
      await connect();
    } catch (e) {
      // ต่อคลาวด์ไม่ได้ไม่ใช่เหตุให้เล่นไม่ได้ ข้อมูลในเครื่องยังอยู่ครบ
      console.warn('[boot] ต่อคลาวด์ไม่สำเร็จ เล่นด้วยข้อมูลในเครื่องต่อ', e);
    }
  }

  await import('./main.js');
}

boot();
