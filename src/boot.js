// ทำไมต้องมีชั้นนี้: โมดูลของเกมอ่าน localStorage ตั้งแต่ตอนถูก import
// (เช่น skins.js หยิบสีขนที่เลือกไว้, gacha.js หยิบจำนวนทอง) ซึ่งใน ES module
// การ import ถูกยกขึ้นไปทำงานก่อนโค้ดบรรทัดแรกเสมอ
//
// ถ้าดึงข้อมูลจากคลาวด์ใน main.js จะสายเกินไป — เกมอ่านค่าเก่าไปแล้ว
// จึงต้องดึงให้เสร็จก่อน แล้วค่อย import ตัวเกมแบบไดนามิก
//
// ที่นี่กู้เฉพาะ session เดิมเท่านั้น ไม่สร้างบัญชีให้เอง — ปุ่มเข้าสู่ระบบอยู่
// ในหน้าเกม (main.js) ซึ่งเรียกทีหลังได้โดยไม่ต้องโหลดหน้าใหม่ เพราะบัญชีที่
// เพิ่งสร้างยังไม่มีข้อมูลบนคลาวด์ให้ต้องเทลงมาทับของที่โมดูลอ่านไปแล้ว
//
// ผลพลอยได้: ถ้าไม่ได้ตั้งคีย์ Supabase ไฟล์นี้แทบไม่ทำอะไรเลย
// ข้ามไปโหลดเกมทันที เกมจึงยังเล่นได้เหมือนก่อนมีระบบคลาวด์ทุกประการ
// ─────────────────────────────────────────────────────────────
import { cloudReady } from './net/cloud.js';

/**
 * ปิดหน้าโหลด
 *
 * หน้าโหลด (#splash) ฝังอยู่ใน index.html พร้อม CSS ของตัวเอง จึงขึ้นตั้งแต่
 * เฟรมแรกโดยไม่ต้องรอไฟล์ไหนเลย — ไฟล์นี้มีหน้าที่แค่เอามันออกตอนเกมพร้อม
 *
 * ── ทำไมต้องรอ raf สองชั้นก่อนซ่อน ──
 * import('./main.js') คืนค่าตอน "โมดูลรันจบ" ซึ่งยังไม่ใช่ตอนที่เบราว์เซอร์
 * วาดผลของมันลงจอ ถ้าซ่อนทันทีจะเห็นเวทีเปล่า ๆ แวบหนึ่งก่อนภาพแรกจะขึ้น
 * รอสองเฟรมแล้วภาพหลังม่านพร้อมแน่นอนก่อนม่านจะเปิด
 *
 * เรียกซ้ำได้ไม่มีผลข้างเคียง (ตัวกันเวลาข้างล่างอาจเรียกชนกับทางปกติ)
 */
function hideSplash() {
  const el = document.getElementById('splash');
  if (!el || el.classList.contains('gone')) return;

  el.classList.add('ready');   // หลอดวิ่งไปสุดก่อน แล้วค่อยจางหาย
  requestAnimationFrame(() => requestAnimationFrame(() => {
    setTimeout(() => {
      el.classList.add('gone');
      // ถอดออกจากหน้าเลยหลังจางจบ ไม่ปล่อยให้ค้างเป็นชั้นโปร่งใสคลุมทั้งจอ
      // ซึ่งจะกินการแตะของเกมทั้งหมดถ้าวันหนึ่งมีใครไปแก้ pointer-events
      el.addEventListener('transitionend', () => el.remove(), { once: true });
      setTimeout(() => el.remove(), 900);   // เผื่อ transitionend ไม่ยิง
    }, 260);
  }));
}

async function boot() {
  if (cloudReady) {
    try {
      const { resume } = await import('./net/sync.js');
      await resume();
    } catch (e) {
      // ต่อคลาวด์ไม่ได้ไม่ใช่เหตุให้เล่นไม่ได้ ข้อมูลในเครื่องยังอยู่ครบ
      console.warn('[boot] ต่อคลาวด์ไม่สำเร็จ เล่นด้วยข้อมูลในเครื่องต่อ', e);
    }
  }

  try {
    await import('./main.js');
  } finally {
    // ใน finally เพราะถ้าโหลดเกมพัง หน้าโหลดต้องหายไปให้เห็นว่าเกิดอะไรขึ้น
    // ไม่ใช่ค้างหมุนอยู่อย่างนั้นตลอดกาลโดยไม่มีใครรู้ว่ามันพังไปแล้ว
    hideSplash();
  }
}

// ตัวกันค้างขั้นสุดท้าย — ถ้าอะไรสักอย่างค้างจนไม่มีใครเรียก hideSplash เลย
// อย่างน้อยผู้เล่นต้องได้เห็นหน้าเกม ไม่ใช่จ้องหน้าโหลดไปเรื่อย ๆ
setTimeout(hideSplash, 15000);

boot();
