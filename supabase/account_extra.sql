-- ─────────────────────────────────────────────────────────────
-- ข้อมูลบัญชีที่เดิมเก็บไว้แค่ในเครื่อง ให้ตามบัญชีไปทุกเครื่อง
--
-- รันไฟล์นี้ใน Supabase → SQL Editor ครั้งเดียว (รันซ้ำได้ ไม่พังของเดิม)
--
-- ── ปัญหาที่แก้ ──
-- แมวที่ปลดล็อก รางวัลเลเวลที่รับแล้ว การ์ดพรสวรรค์/สกิลที่เลือก สเตตัสโปรไฟล์
-- เช็คอินรายวัน ฯลฯ เก็บอยู่แค่ใน localStorage ของเครื่องที่เล่น
--   • เข้าบัญชีเดียวกันจากเครื่องอื่น / ล้างเบราว์เซอร์ → ของพวกนี้หายหมด
--   • รางวัลเลเวลที่รับแล้วไม่มีบันทึกบนคลาวด์ → เครื่องใหม่กดรับรางวัลเลเวลซ้ำได้
--
-- ── ทำไมเป็นคอลัมน์ jsonb ก้อนเดียว ไม่ใช่คอลัมน์ละระบบ ──
-- ตัวเกมรวบ "ทุกคีย์ของบัญชีที่ยังไม่มีคอลัมน์ของตัวเอง" ใส่ก้อนนี้อัตโนมัติ (ดู storage.js)
-- ระบบใหม่ที่เพิ่มในอนาคตจึงขึ้นคลาวด์เองโดยไม่ต้องกลับมารัน SQL เพิ่มทุกครั้ง
--
-- ของที่ตั้งใจไม่ขึ้นคลาวด์: รูปหน้าน้อง (หน้าเกมสัญญากับผู้เล่นว่าเก็บในเครื่องเท่านั้น)
-- และภาพที่ระบายสีเอง (ไฟล์รูปใหญ่ ส่งทุกครั้งที่ซิงก์ไม่คุ้ม)
--
-- ตัวเกมรู้เองว่ารันไฟล์นี้แล้วหรือยัง — ยังไม่รันก็ซิงก์แบบเดิมต่อได้ ไม่พัง
-- ─────────────────────────────────────────────────────────────

alter table public.players
  add column if not exists extra jsonb not null default '{}'::jsonb;

-- กันก้อนนี้บวมผิดปกติ (เช่นมีคนยิง API ใส่ของขยะ) — ของจริงใช้ไม่ถึง 20 KB
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'players_extra_size') then
    alter table public.players
      add constraint players_extra_size check (pg_column_size(extra) < 200000);
  end if;
end $$;
