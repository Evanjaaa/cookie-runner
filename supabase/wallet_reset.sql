-- ตั้งยอดทอง/อัญมณีใหม่: ผู้เล่นใหม่ + รีเซ็ตผู้เล่นทุกคนที่มีอยู่ตอนนี้
--   ทอง 15,000 · อัญมณี 450
--
-- รันใน Supabase → SQL Editor ครั้งเดียว
--
-- ⚠ ส่วนที่ 2 เขียนทับยอดของผู้เล่น "ทุกคน" ถาวร กู้คืนไม่ได้
--   (ผู้เล่นที่มีมากกว่านี้จะลดลง / ที่มีน้อยกว่าจะได้เพิ่ม)
--   ของอื่นไม่แตะ: ชุด สกิน สมบัติ ตีบวก เลเวล คะแนน จดหมาย อยู่ครบ
--
-- หลังรัน: ผู้เล่นที่เปิดเกมค้างไว้ควรรีโหลดหน้า
--   แท็บที่เปิดค้างอยู่ยังจำยอดเก่าไว้ในเครื่อง ถ้าเล่นต่อโดยไม่รีโหลด อาจส่งยอดเก่ากลับขึ้นมาทับ
-- ─────────────────────────────────────────────────────────────

-- ── 1) ผู้เล่นใหม่ (บัญชีที่สร้างหลังจากนี้) ──
alter table public.players alter column gold set default 15000;
alter table public.players alter column gems set default 450;

-- ── 2) รีเซ็ตผู้เล่นทุกคนตอนนี้ ──
update public.players set gold = 15000, gems = 450;

-- ── เช็คผล (ควรเห็นแถวเดียว: 15000 | 450 | จำนวนผู้เล่นทั้งหมด) ──
select gold, gems, count(*) as players from public.players group by gold, gems;
